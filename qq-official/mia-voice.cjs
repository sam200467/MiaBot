//    那正是人设里最重的一条红线，也是这里只放模板、不让模型润色的原因。
//
// 2. **别每句都喵。** 人设里写明了猫语是点缀，连着几轮都用同一种最假。下面这些
//    文案会同时出现在一个群里的连续几条消息里，所以刻意错开：有的带喵哼哼，有的
//    只带 ～ 或 ♪，有的干脆是干话。
//
// 3. **数组是「同一件事换着说」，不是重复抑制的手段。** 抑制那件事由传输层的
//    抑制键负责（official-transport.cjs 的 suppressKey）；这里做多个说法纯粹是
//    因为同一句话反复出现会像系统通知，不像人。数组由 core 的 pickHint 随机挑一句，
//    所以**每一句都要自带完整意思**（含指令名），不能依赖上一句。

